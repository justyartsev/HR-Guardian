# ═════════════════════════════════════════════════════════════════════════
def _prepare_prompt(prompt: str, enable_thinking: bool = None) -> str:
    """Подготовка промпта: добавляет /no_think если режим размышлений выключен"""
    thinking = enable_thinking if enable_thinking is not None else ENABLE_THINKING
    if thinking:
        return prompt
    # Добавляем префикс для отключения thinking в Qwen3
    return f"/no_think\n{prompt}"


def answer(prompt: str, enable_thinking: bool = None) -> str:
    """Синхронная генерация ответа (без потока)"""
    try:
        response = client.chat.completions.create(
            model=MODEL,
            messages=[
                {"role": "system", "content": SYSTEM_MESSAGE},
                {"role": "user", "content": _prepare_prompt(prompt, enable_thinking)}
            ],
            temperature=LLM_OPTIONS["temperature"],
            max_tokens=LLM_OPTIONS["num_predict"],
            extra_body={"options": LLM_OPTIONS}
        )
        return response.choices[0].message.content or ""
    except Exception as e:
        return f"Ошибка LLM: {str(e)[:200]}"


def answer_streaming(prompt: str, enable_thinking: bool = None):
    """Потоковая генерация ответа (streaming)

    Важно: исключения пробрасываются наверх, не возвращайте ошибки через yield!
    """
    prepared_prompt = _prepare_prompt(prompt, enable_thinking)
    thinking_enabled = enable_thinking if enable_thinking is not None else ENABLE_THINKING

    # Добавляем инструкцию для режима размышлений
    system_msg = SYSTEM_MESSAGE
    if thinking_enabled:
        system_msg = SYSTEM_MESSAGE + """

КРИТИЧЕСКИ ВАЖНО - РЕЖИМ РАЗМЫШЛЕНИЙ ВКЛЮЧЁН:

Ты ОБЯЗАН начинать КАЖДЫЙ ответ с тега <think> и заканчивать его тегом </think>.

В блоке <think> ты должен рассуждать ЕСТЕСТВЕННО и РАЗВЁРНУТО, как человек (минимум 3-5 предложений):

<think>
Хорошо, давайте разберёмся с этим вопросом. Сотрудник спрашивает о [тема вопроса].

[Если есть документы:]
Смотрю в базу документов... Вижу информацию в документе "[название]". В нём говорится о [краткое содержание]. Это как раз то, что нужно для ответа. Посмотрим, какие конкретные детали есть...

[Если нет документов:]
Проверяю базу документов... К сожалению, конкретной информации по этому вопросу не нашёл. Это может быть специфичный случай. Нужно честно сказать сотруднику, что такой информации нет в системе, и направить его к HR-специалисту.

[Если это приветствие:]
Это приветствие от сотрудника. Нужно ответить дружелюбно и предложить помощь с их вопросами.

[Если несколько документов:]
Вижу информацию в нескольких документах. Давайте объединим эту информацию, чтобы дать полный ответ. [Название 1] говорит о [суть 1], а [Название 2] уточняет [суть 2].

[Формирую ответ:]
Отвечу [как именно: с цитатой/кратко/с направлением к HR]. Важно быть понятным, развернутым и полезным для сотрудника.
</think>

[Твой ответ пользователю]

ВАЖНО:
- Размышляй РАЗВЁРНУТО (не менее 3-5 предложений в think блоке)
- Размышляй как живой человек, естественным языком
- Не используй шаблонные фразы типа "Анализирую вопрос", "Контекст", "Подход"
- Думай вслух, объясняя свои действия и рассуждения
- Не торопись, думай подробно
- После </think> сразу пиши ответ и ОСТАНАВЛИВАЙСЯ"""
    else:
        system_msg = SYSTEM_MESSAGE + """

ВАЖНО - РЕЖИМ БЫСТРОГО ОТВЕТА:
НЕ используй теги <think> и </think>.
Отвечай сразу, БЕЗ размышлений вслух.
Начинай прямо с ответа пользователю."""

    print(f"[LLM] Streaming: model={MODEL}, thinking={thinking_enabled}, prompt_len={len(prompt)}", flush=True)

    try:
        stream = client.chat.completions.create(
            model=MODEL,
            messages=[
                {"role": "system", "content": system_msg},
                {"role": "user", "content": prepared_prompt}
            ],
            temperature=LLM_OPTIONS["temperature"],
            max_tokens=LLM_OPTIONS["num_predict"],
            stream=True,
            extra_body={"options": LLM_OPTIONS}
        )

        chunk_count = 0
        full_response = ""
        for chunk in stream:
            if chunk.choices and chunk.choices[0].delta.content:
                chunk_count += 1
                content = chunk.choices[0].delta.content
                full_response += content
                yield content

        print(f"[LLM] Stream completed. Total chunks: {chunk_count}", flush=True)
        if thinking_enabled:
            has_think = "<think>" in full_response
            print(f"[LLM] Thinking mode: response has <think> tags: {has_think}", flush=True)
            if not has_think:
                print(f"[LLM] WARNING: Model didn't generate <think> tags. First 200 chars: {full_response[:200]}", flush=True)

    except Exception as e:
        print(f"[LLM] ERROR: {type(e).__name__}: {str(e)}")
        raise